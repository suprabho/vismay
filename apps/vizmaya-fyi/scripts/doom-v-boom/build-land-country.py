#!/usr/bin/env python3
"""
Tag every dot of the doom-v-boom land mask with its country and world region,
so the geography map can fill a country's (or region's) dots instead of
drawing one scaled disc at a centroid.

Usage:
  curl -sSLfO https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
  python3 build-land-country.py ne_50m_admin_0_countries.geojson

Writes app/ai-daily/doom-v-boom/components/landCountry.ts next to landMask.ts.
Regions follow dc_countries (migration 100) for the countries it lists; every
other country falls back to a Natural Earth subregion default.
"""
import json, math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
COMP = os.path.join(HERE, '..', '..', 'app', 'ai-daily', 'doom-v-boom', 'components')
MIGRATION = os.path.join(HERE, '..', '..', '..', '..', 'supabase', 'vizmaya-fyi', 'migrations', '100_dc_geo_layers.sql')

mask_src = open(os.path.join(COMP, 'landMask.ts')).read()
nums = [int(n) for n in re.findall(r'-?\d+', mask_src.split('= [', 1)[1].split(']', 1)[0])]
dots = [(nums[i] / 10, nums[i + 1] / 10) for i in range(0, len(nums), 2)]

vocab = dict(re.findall(r"\('([A-Z]{2})',\s*'[^']*',\s*'(na|ea|eu|me|other)'", open(MIGRATION).read()))

SUB = {
    'Northern America': 'na', 'Central America': 'na',
    'Eastern Asia': 'ea', 'South-Eastern Asia': 'ea',
    'Southern Asia': 'me', 'Western Asia': 'me', 'Northern Africa': 'me',
    'Northern Europe': 'eu', 'Western Europe': 'eu', 'Southern Europe': 'eu', 'Eastern Europe': 'eu',
}
CHAR = {'na': 'n', 'ea': 'e', 'eu': 'u', 'me': 'm', 'other': 'o'}

feats = []
for f in json.load(open(sys.argv[1]))['features']:
    p = f['properties']
    code = p.get('ISO_A2_EH') or p.get('ISO_A2')
    if not code or code == '-99':
        continue
    g = f['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    # Greenland is 'Northern America' to Natural Earth; it would swamp the NA fill.
    region = vocab.get(code) or ('other' if code == 'GL' else SUB.get(p.get('SUBREGION'), 'other'))
    for poly in polys:
        xs = [pt[0] for pt in poly[0]]; ys = [pt[1] for pt in poly[0]]
        feats.append((code, region, poly, (min(xs), min(ys), max(xs), max(ys))))

def in_ring(x, y, ring):
    inside = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]; xj, yj = ring[j][0], ring[j][1]
        if (yi > y) != (yj > y) and x < (xj - xi) * (y - yi) / (yj - yi) + xi:
            inside = not inside
        j = i
    return inside

def ring_dist(x, y, ring):
    best = math.inf
    for i in range(len(ring) - 1):
        ax, ay = ring[i][0], ring[i][1]; bx, by = ring[i + 1][0], ring[i + 1][1]
        dx, dy = bx - ax, by - ay
        t = 0 if dx == dy == 0 else max(0, min(1, ((x - ax) * dx + (y - ay) * dy) / (dx * dx + dy * dy)))
        best = min(best, math.hypot(ax + t * dx - x, ay + t * dy - y))
    return best

out = []
for x, y in dots:
    hit = None
    for code, region, poly, (x0, y0, x1, y1) in feats:
        if x0 <= x <= x1 and y0 <= y <= y1 and in_ring(x, y, poly[0]) and not any(in_ring(x, y, h) for h in poly[1:]):
            hit = (code, region); break
    if hit is None:
        # Coastal dot whose centre falls just offshore: nearest coastline within ~2°.
        best, bd = None, 2.0
        for code, region, poly, (x0, y0, x1, y1) in feats:
            if x0 - bd <= x <= x1 + bd and y0 - bd <= y <= y1 + bd:
                d = ring_dist(x, y, poly[0])
                if d < bd:
                    best, bd = (code, region), d
        hit = best
    out.append(hit)

codes = ''.join(h[0] if h else '--' for h in out)
regs = ''.join(CHAR[h[1]] if h else '-' for h in out)
missing = sum(1 for h in out if h is None)

def chunk(s, n):
    return '\n'.join(f"  '{s[i:i + n]}' +" for i in range(0, len(s), n)).rstrip(' +')

ts = f"""/**
 * Country and region of every dot in LAND_MASK, index-aligned (dot i = pair i).
 * Generated by apps/vizmaya-fyi/scripts/doom-v-boom/build-land-country.py from
 * Natural Earth 1:50m admin-0 — do not edit by hand.
 *
 * LAND_COUNTRY: two chars per dot, ISO 3166-1 alpha-2 ('--' = unassigned).
 * LAND_REGION: one char per dot — n na · e ea · u eu · m me · o other · - none.
 */
export const LAND_COUNTRY =
{chunk(codes, 120)}

export const LAND_REGION =
{chunk(regs, 120)}
"""
open(os.path.join(COMP, 'landCountry.ts'), 'w').write(ts)
print(f'{len(dots)} dots, {missing} unassigned, {len(set(codes[i:i+2] for i in range(0, len(codes), 2)))} countries')
